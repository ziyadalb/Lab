LTR_RE = re.compile(r'(\d{4}-S\d-(?:FE|SE)-Q[\d.]+|M ?111[^،<]*?\.pdf|MATH 111 Class Notes 2024|[A-Za-z_./]+\.(?:py|json|pdf))')


def T(s):
    """Arabic text; $...$ becomes an isolated LTR inline formula; ids and file names are LTR-isolated."""
    s = LTR_RE.sub(lambda m: f'<bdi dir="ltr">{m.group(0)}</bdi>', s)
    s = re.sub(r'⟦(.*?)⟧', lambda m: f'<bdi dir="ltr">{m.group(1)}</bdi>', s)
    parts = s.split('$')
    out = []
    for i, p in enumerate(parts):
        out.append(f'<span class="mi" dir="ltr">{html.escape(p)}</span>' if i % 2 else p)
    return ''.join(out)


def M(tex, cls=''):
    return f'<div class="m {cls}" dir="ltr">{html.escape(tex)}</div>'


def P(s, cls=''):
    return f'<p class="{cls}">{T(s)}</p>'


def UL(items, cls=''):
    return f'<ul class="{cls}">' + ''.join(f'<li>{T(i)}</li>' for i in items) + '</ul>'


def OL(items, cls=''):
    return f'<ol class="{cls}">' + ''.join(f'<li>{T(i)}</li>' for i in items) + '</ol>'


def H(level, id_, title, toc=True, cls=''):
    if toc:
        TOC.append((level, id_, title))
    return f'<h{level} id="{id_}" class="{cls}">{T(title)}</h{level}>'


def STEP(why, tex):
    return f'<div class="step"><div class="why">{T(why)}</div>{M(tex)}</div>'


def BOX(kind, title, *inner):
    icon = {'warn': '⚠', 'check': '✔', 'rule': '◆', 'rec': '★', 'note': '●', 'q': '؟'}[kind]
    return f'<div class="box {kind}"><div class="bt">{icon} {T(title)}</div>' + ''.join(inner) + '</div>'


def LINK(target, text):
    return f'<a href="#{target}">{T(text)}</a> <span class="pgref" data-target="{target}"></span>'


def PG(target):
    return f'<a href="#{target}">ص <span class="pgref" data-target="{target}"></span></a>'


def SRC(s):
    return f'<div class="src">{T(s)}</div>'


